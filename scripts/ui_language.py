def set_language(language):
 global LANG,CONSOLE
 if language not in ('en','zh'):raise ValueError('Unknown language')
 LANG=language;os.environ['ZV1_FTP_LANG']=language;CONSOLE=sys.stdout
def tr(value):
 text=str(value)
 if text in STATUS:
  return text+' — '+STATUS[text][LANG=='zh']
 replacements=[(en,zh) if LANG=='zh' else (zh,en) for en,zh in PAIRS]
 # Exact matches first prevent partial substitutions inside longer messages.
 for source,target in replacements:
  if text==source:return target
 for source,target in sorted(replacements,key=lambda p:len(p[0]),reverse=True):
  if source in text:text=text.replace(source,target)
 return text
def print(*values,**kwargs):builtins.print(*(tr(v) if isinstance(v,str) else v for v in values),**kwargs)
def announce(key):builtins.print(PHASES[key][LANG=='zh'],file=CONSOLE or sys.stdout,flush=True)
